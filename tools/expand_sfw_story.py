def words_of(pool):
    return [w if isinstance(w, dict) else {"text": w, "asStr": True} for w in pool]


def main():
    with open(TARGET, encoding="utf-8") as handle:
        data = json.load(handle)

    taken = {}
    for name, pool in data["pools"].items():
        for word in pool:
            text = word["text"] if isinstance(word, dict) else word
            taken[text] = name

    added, skipped, clashes = 0, 0, []
    for name, words in ADD.items():
        if name not in data["pools"]:
            raise SystemExit(f"没有这个池：{name}")
        pool = data["pools"][name]
        for word in words:
            if word in taken:
                if taken[word] != name:
                    clashes.append(f"{word}（已在 {taken[word]}）")
                else:
                    skipped += 1
                continue
            pool.append(word)
            taken[word] = name
            added += 1

    if clashes:
        raise SystemExit("跨池重复：" + "、".join(clashes))

    data["version"] = "0.9.8.8382-sfw-exp1"

    with open(TARGET, "w", encoding="utf-8") as handle:
        json.dump(data, handle, ensure_ascii=False, indent=2)
        handle.write("\n")

    total = sum(len(v) for v in data["pools"].values())
    print(f"新增 {added} 条，跳过 {skipped} 条，现在共 {total} 条")


if __name__ == "__main__":
    main()
